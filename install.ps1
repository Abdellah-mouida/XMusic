# XMusic installer for Windows (PowerShell). NOT TESTED by the author on Windows - see README "Platform status".
# Creates .\venv, installs dependencies into it, and writes a launcher %LOCALAPPDATA%\XMusic\bin\xmusic.cmd
$ErrorActionPreference = "Stop"
$dir = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $dir
if (-not (Test-Path "venv\Scripts\python.exe")) {
    Write-Host "* creating virtual environment"
    if (Get-Command py -ErrorAction SilentlyContinue) { py -3 -m venv venv } else { python -m venv venv }
}
Write-Host "* installing dependencies"
& "venv\Scripts\python.exe" -m pip install --disable-pip-version-check -q -r requirements.txt
& "venv\Scripts\python.exe" -c "import miniaudio, mutagen; print('* dependencies OK')"
$bin = Join-Path $env:LOCALAPPDATA "XMusic\bin"
New-Item -ItemType Directory -Force -Path $bin | Out-Null
$py = Join-Path $dir "venv\Scripts\python.exe"
$app = Join-Path $dir "xmusic.py"
"@echo off`r`nrem XMusic launcher (generated by install.ps1)`r`n`"$py`" `"$app`" %*" | Set-Content -Encoding ASCII (Join-Path $bin "xmusic.cmd")
Write-Host "* launcher written to $bin\xmusic.cmd  (add that folder to PATH, or run: $py $app)"
Write-Host "Done.  Run:  xmusic --music-dir `"$env:USERPROFILE\Music`""
