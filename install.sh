#!/usr/bin/env bash
# XMusic installer for Linux and macOS: creates ./venv (if missing), installs dependencies into it and adds a
# launcher at ~/.local/bin/xmusic.  Never uses sudo, never touches system Python or your music.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PY="${PYTHON:-python3}"
BIN="${XDG_BIN_HOME:-$HOME/.local/bin}"
cd "$DIR"

if [ ! -x venv/bin/python ]; then
  echo "• creating virtual environment in $DIR/venv"
  "$PY" -m venv venv || { echo "error: could not create a venv. On Ubuntu:  sudo apt install python3-venv"; exit 1; }
fi
echo "• installing dependencies (miniaudio, mutagen) into the venv"
venv/bin/python -m pip install --disable-pip-version-check -q -r requirements.txt
venv/bin/python -c "import miniaudio, mutagen; print('• dependencies OK')"
if venv/bin/python -c 'import sys; sys.exit(0 if sys.version_info >= (3, 13) else 1)'; then
  venv/bin/python -m pip install --disable-pip-version-check -q audioop-lts \
    || echo "  (optional audioop-lts not installed; XMusic will use its pure-Python volume path)"
fi

mkdir -p "$BIN"
cat > "$BIN/xmusic" <<LAUNCH
#!/bin/sh
# XMusic launcher (generated by install.sh)
exec "$DIR/venv/bin/python" "$DIR/xmusic.py" "\$@"
LAUNCH
chmod +x "$BIN/xmusic"
echo "• launcher written to $BIN/xmusic"
case ":$PATH:" in *":$BIN:"*) ;; *) echo "  note: $BIN is not on your PATH; add it, or run: $DIR/venv/bin/python $DIR/xmusic.py";; esac
echo "Done.  Run:  xmusic --music-dir ~/Music"
