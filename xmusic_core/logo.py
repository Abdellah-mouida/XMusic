def kali_lines() -> list[str]:
    """Exact, unscaled 17-row Kali dragon supplied for the dedicated --kali layout."""
    return _KALI_ART.splitlines()


def kali_width() -> int:
    return max((len(line) for line in kali_lines()), default=0)


def rows(tier: str, kali: bool = False) -> list[list[str]]:
    """Return display glyphs per row; Kali art is never downsampled."""
    lines = kali_lines() if kali else list(XMUSIC_ART)
    width = max((len(line) for line in lines), default=0)
    return [list(line.ljust(width, "⠀" if kali else " ")) for line in lines]


def width(tier: str, kali: bool = False) -> int:
    return kali_width() if kali else max(map(len, XMUSIC_ART))


def height(tier: str, kali: bool = False) -> int:
    return len(kali_lines()) if kali else len(XMUSIC_ART)


