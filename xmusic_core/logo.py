def _compact_kali(tier: str) -> list[str]:
    source = [line.rstrip() for line in _KALI_ART.splitlines()]
    step = 2 if tier == "big" else 3
    width = 46 if tier == "big" else 38
    out = []
    for line in source[::step]:
        line = line.strip(" \u2800")
        if not line:
            continue
        if len(line) > width:
            ratio = len(line) / width
            reduced = []
            for col in range(width):
                start = int(col * ratio)
                end = max(int((col + 1) * ratio), start + 1)
                segment = line[start:end]
                reduced.append(next((ch for ch in segment if ch not in " \u2800"), " "))
            line = "".join(reduced)
        out.append(line)
    return out


def rows(tier: str, kali: bool = False) -> list[list[str]]:
    """Return display glyphs per row for the selected banner."""
    lines = _compact_kali(tier) if kali else list(XMUSIC_ART)
    width = max((len(line) for line in lines), default=0)
    return [list(line.ljust(width)) for line in lines]


def width(tier: str, kali: bool = False) -> int:
    return max((len(line) for line in (_compact_kali(tier) if kali else XMUSIC_ART)), default=0)


def height(tier: str, kali: bool = False) -> int:
    return len(_compact_kali(tier) if kali else XMUSIC_ART)


