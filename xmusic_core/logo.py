XMUSIC_KALI_SCALE = 1


def xmusic_lines(scale: int = XMUSIC_KALI_SCALE) -> list[str]:
    """Enlarge untouched XMusic block art evenly in both axes.

    Nearest-neighbour cell scaling: each original glyph is repeated
    horizontally and each source row vertically. No redraw, distortion,
    or cropping is applied.
    """
    if not isinstance(scale, int) or scale < 1:
        raise ValueError("scale must be a positive integer")
    return [
        "".join(ch * scale for ch in line)
        for line in XMUSIC_ART
        for _ in range(scale)
    ]


def fit_lines(lines: list[str] | tuple[str, ...], max_width: int, max_height: int) -> list[str]:
    """Fit terminal art proportionally into a non-empty viewport."""
    if max_width <= 0 or max_height <= 0 or not lines:
        return []
    src_h = len(lines)
    src_w = max((len(line) for line in lines), default=0)
    if not src_w or not src_h:
        return []
    scale = min(1.0, max_width / src_w, max_height / src_h)
    dst_w = max(1, min(max_width, round(src_w * scale)))
    dst_h = max(1, min(max_height, round(src_h * scale)))
    padded = [line.ljust(src_w) for line in lines]
    return [
        "".join(
            padded[min(src_h - 1, int((y + 0.5) * src_h / dst_h))]
                   [min(src_w - 1, int((x + 0.5) * src_w / dst_w))]
            for x in range(dst_w)
        )
        for y in range(dst_h)
    ]


def kali_lines() -> list[str]:
    """Exact, unscaled 17-row Kali dragon supplied for the dedicated --kali layout."""
    return _KALI_ART.splitlines()


def kali_width() -> int:
    return max((len(line) for line in kali_lines()), default=0)


def rows(tier: str, kali: bool = False) -> list[list[str]]:
    """Return display glyphs per row; Kali art is never downsampled."""
    lines = kali_lines() if kali else list(XMUSIC_ART)
    width = max((len(line) for line in lines), default=0)
    return [list(line.ljust(width, "⠀" if kali else " ")) for line in lines]


def width(tier: str, kali: bool = False) -> int:
    return kali_width() if kali else max(map(len, XMUSIC_ART))


def height(tier: str, kali: bool = False) -> int:
    return len(kali_lines()) if kali else len(XMUSIC_ART)


